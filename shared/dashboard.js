/* nighthq live dashboard — polls the unified backend and renders stat
   panels. No build step, no framework — matches the rest of the portfolio. */

const CONFIG = window.DASH_CONFIG || { BACKEND_URL: 'http://localhost:4100' };
const REFRESH_MS = 60000;
const PW_KEY = 'nighthq_dash_pw';

function $(sel) { return document.querySelector(sel); }

async function fetchJSON(path, opts = {}) {
  const pw = sessionStorage.getItem(PW_KEY);
  const res = await fetch(`${CONFIG.BACKEND_URL}${path}`, {
    ...opts,
    headers: { ...(opts.headers || {}), ...(pw ? { 'x-dashboard-password': pw } : {}) },
  });
  if (res.status === 401) { showAuthGate(); throw new Error('Unauthorized'); }
  if (!res.ok) throw new Error(`${path} → ${res.status}`);
  return res.json();
}

// ── password gate ────────────────────────────────────────────────────────
function showAuthGate() {
  const gate = document.getElementById('auth-gate');
  const content = document.getElementById('dashboard-content');
  if (gate) gate.style.display = 'flex';
  if (content) content.style.display = 'none';
}

function hideAuthGate() {
  const gate = document.getElementById('auth-gate');
  const content = document.getElementById('dashboard-content');
  if (gate) gate.style.display = 'none';
  if (content) content.style.display = 'block';
}

async function checkPassword(password) {
  const res = await fetch(`${CONFIG.BACKEND_URL}/api/auth/check`, {
    method: 'POST',
    headers: { 'content-type': 'application/json' },
    body: JSON.stringify({ password }),
  });
  return res.ok;
}

async function initAuth() {
  const stored = sessionStorage.getItem(PW_KEY);
  if (stored && await checkPassword(stored)) {
    hideAuthGate();
    startDashboard();
    return;
  }
  sessionStorage.removeItem(PW_KEY);
  showAuthGate();

  const submit = document.getElementById('auth-submit');
  const input  = document.getElementById('auth-input');
  const error  = document.getElementById('auth-error');
  if (!submit || !input) return;

  const attempt = async () => {
    const ok = await checkPassword(input.value);
    if (ok) {
      sessionStorage.setItem(PW_KEY, input.value);
      error.style.display = 'none';
      hideAuthGate();
      startDashboard();
    } else {
      error.style.display = 'block';
    }
  };
  submit.addEventListener('click', attempt);
  input.addEventListener('keydown', e => { if (e.key === 'Enter') attempt(); });
}

function fmtMoney(cents, currency = 'USD') {
  return new Intl.NumberFormat('en-US', { style: 'currency', currency }).format((cents || 0) / 100);
}

function fmtNum(n) {
  return new Intl.NumberFormat('en-US').format(n || 0);
}

function badge(source) {
  return source === 'live'
    ? `<span class="badge live">Live</span>`
    : `<span class="badge mock">Mock</span>`;
}

function sparkline(points, valueKey) {
  const values = points.map(p => p[valueKey]);
  const max = Math.max(...values, 1);
  const min = Math.min(...values, 0);
  const range = max - min || 1;
  const w = 280, h = 40;
  const step = w / Math.max(points.length - 1, 1);
  const coords = values.map((v, i) => {
    const x = i * step;
    const y = h - ((v - min) / range) * h;
    return [x, y];
  });
  const line = coords.map(([x, y], i) => `${i === 0 ? 'M' : 'L'}${x.toFixed(1)},${y.toFixed(1)}`).join(' ');
  const fill = `${line} L${w},${h} L0,${h} Z`;
  return `<svg class="sparkline" viewBox="0 0 ${w} ${h}" preserveAspectRatio="none">
    <path class="fill" d="${fill}"></path>
    <path d="${line}"></path>
  </svg>`;
}

function setHTML(id, html) {
  const el = document.getElementById(id);
  if (el) el.innerHTML = html;
}

async function loadConnections() {
  try {
    const d = await fetchJSON('/api/connections');
    const tiles = d.services.map(s => `
      <div class="conn-tile">
        <span class="conn-dot ${s.status}"></span>
        <div>
          <div class="conn-name">${s.name}</div>
          <div class="conn-detail">${s.status} · ${s.detail}</div>
        </div>
      </div>
    `).join('');
    setHTML('connections-panel', `
      <div class="panel-head"><div class="panel-title">Connected Properties</div></div>
      <div class="conn-grid">${tiles}</div>
    `);
  } catch (e) {
    setHTML('connections-panel', `<div class="err">Connection status unavailable.</div>`);
  }
}

