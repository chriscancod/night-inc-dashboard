function refreshAll() {
  loadConnections();
  loadInsight();
  loadPurchases();
  loadDownloads();
  loadLeaderboard();
  loadWinner();
  loadWinnersHistory();
  loadEngagement();
  const stamp = document.getElementById('last-updated');
  if (stamp) stamp.textContent = `Last updated ${new Date().toLocaleTimeString()}`;
}

function startDashboard() {
  refreshAll();
  setInterval(refreshAll, REFRESH_MS);
}

